"""Render content/episode-XXX/claims.json + fact_check.csv as a Markdown fact-check table.

One row per claim: ID, type, claim, narration segment IDs, source (with link), evidence, method/caveat.
Usage: python python/fact_table.py --episode 002 --out episode002/fact_check.md
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def cell(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--episode", default="002")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    base = ROOT / "content" / f"episode-{a.episode}"
    claims = json.loads((base / "claims.json").read_text())["claims"]
    rows = list(csv.DictReader((base / "fact_check.csv").open()))
    src = {r[next(iter(r))]: r for r in rows}
    ep = json.loads((base / "episode.json").read_text())
    seg_text = {f"{s['id']}-{g['id']}": g["text"] for s in ep["scenes"] for g in s["segments"]}
    used = {seg for c in claims for seg in c["segments"]}
    missing = [s for c in claims for s in c["segments"] if s not in seg_text]
    out = [f"# Fact-check table — Episode {a.episode}: {ep['title']}", "",
           f"Generated by `python/fact_table.py` from `content/episode-{a.episode}/claims.json` and `fact_check.csv`. "
           "Segment IDs refer to `content/episode-" + a.episode + "/episode.json` (scene-segment).", "",
           f"{len(claims)} claims · {len(used)} narration segments carry a claim · unknown segment IDs: {len(missing)}", "",
           "| ID | Type | Claim | Narration | Source | Evidence | Method / caveat |", "|---|---|---|---|---|---|---|"]
    for c in claims:
        links = []
        for s in c["sources"]:
            r = src.get(s)
            url = next((r[k] for k in r if "url" in k.lower() or k.lower() in ("link", "source")), "") if r else ""
            links.append(f"[{s}]({url})" if url.startswith("http") else s)
        out.append("| " + " | ".join(cell(x) for x in [c["id"], c["type"], c["claim"], ", ".join(c["segments"]), ", ".join(links) or "—", c["evidence"], c.get("method_or_caveat", "")]) + " |")
    if rows:
        out += ["", "## Sources", "", "| " + " | ".join(rows[0].keys()) + " |", "|---" * len(rows[0]) + "|"]
        out += ["| " + " | ".join(cell(v) for v in r.values()) + " |" for r in rows]
    Path(ROOT / a.out).parent.mkdir(parents=True, exist_ok=True)
    (ROOT / a.out).write_text("\n".join(out) + "\n")
    print(f"{a.out}: {len(claims)} claims, {len(rows)} sources, {len(missing)} unknown segment IDs")


if __name__ == "__main__":
    main()
